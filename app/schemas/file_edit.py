"""Schemas for hot file editing, diff proposals, and confirmations."""

from datetime import UTC, datetime

from pydantic import BaseModel, ConfigDict, Field


class FileEditRequest(BaseModel):
    """Request to propose an edit for a file in the active project workspace."""

    model_config = ConfigDict(str_strip_whitespace=True)

    project_id: str = Field(..., min_length=1, description="ID del proyecto")
    file_path: str = Field(
        ..., min_length=1, description="Ruta relativa del archivo en el workspace"
    )
    instruction: str = Field(
        ..., min_length=1, max_length=4000, description="Instrucción de edición"
    )
    session_id: str | None = Field(
        default=None, description="ID de sesión de chat opcional para registrar el evento"
    )


class FileEditProposal(BaseModel):
    """Proposal generated by an agent containing unified diff and token for confirmation."""

    model_config = ConfigDict(frozen=True)

    edit_token: str = Field(..., description="Token UUID para confirmar o descartar")
    agent_id: str
    project_id: str
    file_path: str
    original_content: str
    proposed_content: str
    diff: str
    explanation: str
    created_at: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())


class FileEditConfirmResponse(BaseModel):
    """Result of confirming and applying a proposed file edit."""

    model_config = ConfigDict(frozen=True)

    success: bool
    message: str
    project_id: str
    file_path: str
    backup_path: str | None
    applied_at: str = Field(default_factory=lambda: datetime.now(UTC).isoformat())


class FileEditRejectResponse(BaseModel):
    """Result of rejecting a proposed file edit."""

    model_config = ConfigDict(frozen=True)

    success: bool
    message: str
    edit_token: str


class ProjectFileInfo(BaseModel):
    """Metadata of a file within a project workspace."""

    model_config = ConfigDict(frozen=True)

    path: str
    size: int
    is_dir: bool
    last_modified: str


class ProjectFileContent(BaseModel):
    """Full text content of a workspace file."""

    model_config = ConfigDict(frozen=True)

    project_id: str
    file_path: str
    content: str
    size: int
